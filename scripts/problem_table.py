#!/usr/bin/env python3
"""Generate docs/PROBLEMS.md: one row per problem, read from PillowProblems/PNN.lean.

For each problem it records Carroll's subject, the opening words of the question, the
`**Status.**` line and the public theorems. `--check` exits non-zero if a problem is
missing, has a TODO status, or claims "proved" while the file contains `sorry`.
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DECL = re.compile(r'^(?:@\[[^\]]*\]\s*)?(?:protected\s+|noncomputable\s+)*(theorem|lemma)\s+([^\s:(\[{]+)', re.M)


def strip_comments(t: str) -> str:
    t = re.sub(r'/-.*?-/', '', t, flags=re.S)
    return re.sub(r'--[^\n]*', '', t)


def main() -> int:
    sys.stdout.reconfigure(encoding='utf-8')
    check = '--check' in sys.argv
    data = {p['n']: p for p in json.loads((ROOT / 'data' / 'problems.json').read_text(encoding='utf-8'))['problems']}
    rows, problems = [], []
    for n in range(1, 73):
        f = ROOT / 'PillowProblems' / f'P{n:02d}.lean'
        if not f.exists():
            problems.append(f'problem {n}: file missing'); continue
        text = f.read_text(encoding='utf-8')
        m = re.search(r'\*\*Status\.\*\*\s*(.+)', text)
        status = m.group(1).strip() if m else 'MISSING'
        code = strip_comments(text)
        decls = [d.group(2) for d in DECL.finditer(code)]
        has_sorry = re.search(r'\bsorry\b', code) is not None
        if 'TODO' in status or status == 'MISSING':
            problems.append(f'problem {n}: status not filled')
        if status.startswith('proved') and has_sorry:
            problems.append(f'problem {n}: status says proved but the file uses sorry')
        if status.startswith('proved') and not any(d.startswith(f'problem{n}') for d in decls):
            problems.append(f'problem {n}: no theorem named problem{n}…')
        q = ' '.join(data[n]['question'].split())
        words = q.split()
        first = ' '.join(words[:14]) + (' …' if len(words) > 14 else '')
        rows.append((n, ', '.join(data[n]['subjects']), first, status, decls, has_sorry))
    counts = {}
    for r in rows:
        key = r[3].split(':')[0].strip()
        counts[key] = counts.get(key, 0) + 1
    out = ['# Problem map: *Pillow-Problems* (4th ed., 1895)', '',
           'Generated by `scripts/problem_table.py` from `PillowProblems/PNN.lean`. Do not edit by hand.', '',
           '| Status | Problems |', '|---|---|']
    out += [f'| {k} | {v} |' for k, v in sorted(counts.items(), key=lambda kv: -kv[1])]
    out += ['', '| No. | Subject | Question (opening words) | Status | Theorems |', '|---|---|---|---|---|']
    for n, subj, first, status, decls, has_sorry in rows:
        first = first.replace('|', '\\|')
        shown = ', '.join(f'`{d}`' for d in decls if d.startswith(f'problem{n}')) or '—'
        flag = ' ⚠️ sorry' if has_sorry else ''
        out.append(f'| [{n}](PillowProblems/P{n:02d}.lean) | {subj} | {first} | {status}{flag} | {shown} |'
                   .replace('](PillowProblems', '](../PillowProblems'))
    (ROOT / 'docs' / 'PROBLEMS.md').write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'{len(rows)} problems; ' + ', '.join(f'{k}: {v}' for k, v in counts.items()))
    for p in problems:
        print('PROBLEM:', p)
    return 1 if (check and problems) else 0


if __name__ == '__main__':
    sys.exit(main())
