#!/usr/bin/env python3
"""Generate Benchmark/PNN.lean from PillowProblems/PNN.lean: the same statements with every
public theorem's proof replaced by `sorry`.

* public `theorem` / `lemma`: statement kept, proof replaced by `by sorry`;
* `private theorem` / `private lemma` and `example`: removed (with their doc comments);
* everything else (doc blocks, definitions, structures, instances, namespaces) is kept verbatim,
  so the statements mean exactly what they mean in the reference solutions.

The result is a set of formal problems for evaluating provers: `lake build Benchmark` should
succeed with one `sorry` warning per theorem. Regenerate after changing any problem file.
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOP = re.compile(r'^(?:@\[|/--|/-!|private\b|protected\b|noncomputable\b|theorem\b|lemma\b|def\b|abbrev\b|'
                 r'structure\b|class\b|inductive\b|instance\b|example\b|namespace\b|end\b|open\b|section\b|'
                 r'variable\b|set_option\b|attribute\b|local\b|scoped\b|notation\b|macro\b|import\b|universe\b|#)')
THM = re.compile(r'^(?:@\[[^\]]*\]\s*)?(private\s+)?(?:protected\s+|noncomputable\s+)*(theorem|lemma|example)\b')


def chunks(text: str):
    """Split into top-level items: each starts at a column-0 line that begins an item."""
    out, cur, in_block = [], [], 0
    prefix_only = False  # cur holds only a doc comment and/or attribute lines so far
    for ln in text.split('\n'):
        starts = in_block == 0 and bool(ln) and not ln[0].isspace() and TOP.match(ln) is not None
        is_prefix = starts and (ln.startswith('/--') or (ln.startswith('@[') and re.fullmatch(r'@\[[^\]]*\]\s*', ln)))
        if starts:
            if cur and not prefix_only:
                out.append(cur); cur = []
            prefix_only = bool(is_prefix) and (prefix_only or not cur)
        cur.append(ln)
        in_block = max(in_block + ln.count('/-') - ln.count('-/'), 0)
    if cur:
        out.append(cur)
    return out


def statement_end(body: str) -> int:
    """Index of the top-level `:=` that starts the proof (or -1).

    A `:=` that belongs to a `let`/`have` binding inside the statement is skipped."""
    depth, i, pending = 0, 0, 0
    while i < len(body) - 1:
        c = body[i]
        if c in '([{⟨':
            depth += 1
        elif c in ')]}⟩':
            depth -= 1
        elif depth == 0 and re.match(r'(let|have)\b', body[i:]) and (i == 0 or not (body[i - 1].isalnum() or body[i - 1] in "_.'")):
            pending += 1
        elif depth == 0 and body.startswith(':=', i):
            if pending:
                pending -= 1
            else:
                return i
            i += 2
            continue
        i += 1
    return -1


def convert(text: str) -> str:
    out = []
    for ch in chunks(text):
        block = '\n'.join(ch)
        doc = ''
        rest = block
        if block.startswith('/--'):
            j = block.find('-/') + 2
            doc, rest = block[:j], block[j:].lstrip('\n')
        m = THM.match(rest)
        if not m:
            out.append(block); continue
        if m.group(1) or m.group(2) == 'example':
            continue  # private helper or example: drop
        k = statement_end(rest)
        if k < 0:
            raise SystemExit(f'cannot find := in:\n{rest[:300]}')
        stmt = rest[:k].rstrip()
        trailing = '\n' * (len(rest) - len(rest.rstrip('\n')))
        out.append((doc + '\n' if doc else '') + stmt + ' := by\n  sorry' + (trailing or '\n'))
    res = '\n'.join(out)
    return re.sub(r'\n{3,}', '\n\n', res)


def main() -> int:
    sys.stdout.reconfigure(encoding='utf-8')
    (ROOT / 'Benchmark').mkdir(exist_ok=True)
    files = sorted((ROOT / 'PillowProblems').glob('P[0-9][0-9].lean'))
    for f in files:
        (ROOT / 'Benchmark' / f.name).write_text(convert(f.read_text(encoding='utf-8')), encoding='utf-8')
    (ROOT / 'Benchmark.lean').write_text(
        ''.join(f'import Benchmark.{f.stem}\n' for f in files) +
        '\n/-! Formal statements of all 72 *Pillow-Problems* with proofs replaced by `sorry`.\n'
        'Generated by `scripts/make_benchmark.py`; do not edit by hand. -/\n', encoding='utf-8')
    print(f'wrote {len(files)} benchmark files')
    return 0


if __name__ == '__main__':
    sys.exit(main())
